const express = require('express');
const bodyParser = require('body-parser');
const path = require('path');
const twilio = require('twilio');

const app = express();
const PORT = process.env.PORT || 3000;

const accountSid = process.env.TWILIO_ACCOUNT_SID;
const authToken = process.env.TWILIO_AUTH_TOKEN;
const twilioClient = twilio(accountSid, authToken);

// Twilio sends status updates as application/x-www-form-urlencoded
app.use(bodyParser.urlencoded({ extended: false }));
app.use(bodyParser.json());

app.use(express.static(path.join(__dirname, 'public')));

// 1. Required Execution Endpoint called by Journey Builder
app.post('/execute', async (req, res) => {
    try {
        const requestBody = req.body;
        console.log('--- Processing contact from Journey Builder ---');

        const inArguments = requestBody.inArguments || {};
        const contactPhone = inArguments.phoneNumber; 
        
        // Dynamic public URL generated by Render for the status callback
        // Replace with your actual Render domain or use process.env.RENDER_EXTERNAL_URL if available
        const statusCallbackUrl = 'https://sfmc-custom-activity-i6x2.onrender.com/twilio-status';

        // Trigger SMS with status callback tracking enabled
        const message = await twilioClient.messages.create({
            body: 'Hello! This is a custom message tracking delivery status.',
            from: process.env.TWILIO_PHONE_NUMBER,
            to: contactPhone,
            statusCallback: statusCallbackUrl // Tells Twilio where to send delivery reports
        });

        console.log(`Message triggered successfully. SID: ${message.sid}`);
        return res.status(200).json({ status: 'ok' });

    } catch (error) {
        console.error('Error triggering message (Simulated):', error.message);
        // Return 200 during testing to prevent stalling the SFMC journey
        return res.status(200).json({ status: 'simulated_ok', error: error.message });
    }
});

// 2. NEW ENDPOINT: Webhook to receive Twilio Delivery Status Reports
app.post('/twilio-status', (req, res) => {
    // Twilio sends MessageSid, MessageStatus (sent, delivered, undelivered, failed), etc.
    const messageSid = req.body.MessageSid;
    const messageStatus = req.body.MessageStatus;
    const errorCode = req.body.ErrorCode || 'None';

    console.log('--- Twilio Delivery Report Received ---');
    console.log(`Message SID: ${messageSid}`);
    console.log(`Delivery Status: ${messageStatus}`);
    
    if (messageStatus === 'failed' || messageStatus === 'undelivered') {
        console.log(`Failure Reason / Error Code: ${errorCode}`);
    }

    // Always respond with a 200 OK to Twilio to acknowledge receipt of the webhook
    return res.status(200).send('Status received');
});

app.post('/save', (req, res) => res.status(200).json({ status: 'ok' }));
app.post('/validate', (req, res) => res.status(200).json({ status: 'ok' }));
app.post('/publish', (req, res) => res.status(200).json({ status: 'ok' }));

app.listen(PORT, () => {
    console.log(`Server successfully running on port ${PORT}`);
});
